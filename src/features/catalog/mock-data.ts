function exam(
  slug: string,
  title: string,
  questionCount: number,
  durationMin: number,
  sectionNames: string[],
): IncludedExam {
  return { slug, title, questionCount, durationMin, sectionNames };
}

function examSeries(prefix: string, slugPrefix: string, n: number, q: number, d: number, s: string[]) {
  return Array.from({ length: n }, (_, i) =>
    exam(`${slugPrefix}-paket-${i + 1}`, `${prefix} Paket ${i + 1}`, q, d, s),
  );
}

