// Bab 1–2 setiap kelas gratis untuk pengguna yang sudah masuk (G.4.10).
function course(
  slug: string,
  title: string,
  chapters: [string, string[]][],
  videoCount: number,
): IncludedCourse {
  const sections = chapters.map(([t, lessons], i) => ({ title: t, isFree: i < 2, lessons }));
  return {
    slug,
    title,
    sections,
    videoCount,
    lessonCount: sections.reduce((n, s) => n + s.lessons.length, 0),
  };
}

